import java.util.*;
import java.io.*;

public class Main {
    public static final int MOD = 10007;
    
    public static int[][][][] dp;

    public static void main(String[] args) throws IOException {
        BufferedReader br = new BufferedReader(new InputStreamReader(System.in));
        int n = Integer.parseInt(br.readLine());
        
        dp = new int[n + 2][2][2][2];

        dp[1][0][0][0] = 1;

        for (int i = 1; i <= n; i++) {
            
            // 1. [0][0][0] : 현재 열이 깨끗하게 비어있는 경우
            // - 가로 블록(1x2) 3개 배치 -> 다음 열은 모두 채워짐 [1][1][1]
            // - 세로 블록(2x1) 1개(1,2행) + 가로 블록 1개(3행) -> 다음 열 [0][0][1]
            // - 가로 블록 1개(1행) + 세로 블록(2x1) 1개(2,3행) -> 다음 열 [1][0][0]
            if (dp[i][0][0][0] > 0) {
                int val = dp[i][0][0][0];
                dp[i + 1][1][1][1] = (dp[i + 1][1][1][1] + val) % MOD;
                dp[i + 1][0][0][1] = (dp[i + 1][0][0][1] + val) % MOD;
                dp[i + 1][1][0][0] = (dp[i + 1][1][0][0] + val) % MOD;
            }

            // 2. [0][0][1] : 3행만 이미 채워져서 1, 2행이 비어있는 경우
            // - 1, 2행에 세로 블록(2x1) 1개 배치 -> 다음 열은 모두 비어있음 [0][0][0]
            // - 1, 2행에 가로 블록(1x2) 2개 배치 -> 다음 열 [1][1][0]
            if (dp[i][0][0][1] > 0) {
                int val = dp[i][0][0][1];
                dp[i + 1][0][0][0] = (dp[i + 1][0][0][0] + val) % MOD;
                dp[i + 1][1][1][0] = (dp[i + 1][1][1][0] + val) % MOD;
            }

            // 3. [0][1][0] : 2행만 채워져서 1, 3행이 비어있는 경우
            // - 1, 3행에 가로 블록(1x2) 2개 배치 -> 다음 열 [1][0][1]
            // (세로 블록은 인접한 행끼리만 놓을 수 있으므로 떨어져 있는 1,3행에는 세로 블록 배치 불가)
            if (dp[i][0][1][0] > 0) {
                int val = dp[i][0][1][0];
                dp[i + 1][1][0][1] = (dp[i + 1][1][0][1] + val) % MOD;
            }

            // 4. [1][0][0] : 1행만 채워져서 2, 3행이 비어있는 경우
            // - 2, 3행에 세로 블록(2x1) 1개 배치 -> 다음 열은 모두 비어있음 [0][0][0]
            // - 2, 3행에 가로 블록(1x2) 2개 배치 -> 다음 열 [0][1][1]
            if (dp[i][1][0][0] > 0) {
                int val = dp[i][1][0][0];
                dp[i + 1][0][0][0] = (dp[i + 1][0][0][0] + val) % MOD;
                dp[i + 1][0][1][1] = (dp[i + 1][0][1][1] + val) % MOD;
            }

            // 5. [0][1][1] : 2, 3행이 이미 채워져서 1행만 비어있는 경우
            // - 1행에 가로 블록(1x2) 1개 배치 -> 다음 열 [1][0][0]
            if (dp[i][0][1][1] > 0) {
                int val = dp[i][0][1][1];
                dp[i + 1][1][0][0] = (dp[i + 1][1][0][0] + val) % MOD;
            }

            // 6. [1][0][1] : 1, 3행이 이미 채워져서 2행만 비어있는 경우
            // - 2행에 가로 블록(1x2) 1개 배치 -> 다음 열 [0][1][0]
            if (dp[i][1][0][1] > 0) {
                int val = dp[i][1][0][1];
                dp[i + 1][0][1][0] = (dp[i + 1][0][1][0] + val) % MOD;
            }

            // 7. [1][1][0] : 1, 2행이 이미 채워져서 3행만 비어있는 경우
            // - 3행에 가로 블록(1x2) 1개 배치 -> 다음 열 [0][0][1]
            if (dp[i][1][1][0] > 0) {
                int val = dp[i][1][1][0];
                dp[i + 1][0][0][1] = (dp[i + 1][0][0][1] + val) % MOD;
            }

            // 8. [1][1][1] : 모든 행이 이미 채워져서 비어있는 칸이 없는 경우
            // - 이번 열에는 블록을 놓지 않고 그대로 넘어감 -> 다음 열 [0][0][0]
            if (dp[i][1][1][1] > 0) {
                int val = dp[i][1][1][1];
                dp[i + 1][0][0][0] = (dp[i + 1][0][0][0] + val) % MOD;
            }
        }

        System.out.print(dp[n + 1][0][0][0]);
    }
}
